    // ----- Table window -----
    public void showTable(ArrayList<MediaReview> reviews) {
        if (tableFrame == null) {
            buildTableWindow();
        }
        refreshTable(reviews);
        tableFrame.setVisible(true);
        tableFrame.toFront();
    }

    // Reloads the table (only if the table window has been opened)
    public void refreshTable(ArrayList<MediaReview> reviews) {
        if (tableModel == null) {
            return;
        }
        tableModel.setReviews(reviews);
        statusLabel.setText(" Status: Ready. " + reviews.size() + " item(s) loaded.");
    }

    // Separate window with a JTable that lists every review
    private void buildTableWindow() {
        tableModel = new MediaReviewTableModel(new ArrayList<MediaReview>());
        reviewTable = new JTable(tableModel);
        reviewTable.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        reviewTable.getColumnModel().getColumn(0).setPreferredWidth(35);
        reviewTable.getColumnModel().getColumn(2).setPreferredWidth(50);
        reviewTable.getColumnModel().getColumn(6).setPreferredWidth(250);

        // Clicking a row tells the controller which review was picked
        reviewTable.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                int row = reviewTable.getSelectedRow();
                if (row != -1) {
                    controller.reviewSelected(tableModel.getReviewAt(row));
                }
            }
        });

        statusLabel = new JLabel(" ");

        tableFrame = new JFrame("All Reviews");
        tableFrame.setDefaultCloseOperation(JFrame.HIDE_ON_CLOSE);
        tableFrame.setLayout(new BorderLayout());
        tableFrame.add(new JLabel(" Click a row to load it for Update or Delete."), BorderLayout.NORTH);
        tableFrame.add(new JScrollPane(reviewTable), BorderLayout.CENTER);
        tableFrame.add(statusLabel, BorderLayout.SOUTH);
        tableFrame.setSize(800, 300);
        tableFrame.setLocationRelativeTo(this);
    }

