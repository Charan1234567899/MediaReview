    // Dropdown items are "0 - 1", "1", "1 - 2", "2", ... "5"
    // so index 0 -> 0.5, index 1 -> 1.0, index 2 -> 1.5 ... index 9 -> 5.0
    public double getScoreInput() {
        return (Rating_DropDown.getSelectedIndex() + 1) / 2.0;
    }

    // ----- Changing what the window shows -----

    // Puts a review's values into the input boxes so it can be updated or deleted
    public void fillForm(MediaReview review) {
        Title_TextBox.setText(review.getTitle());
        setDropDownFromScore(review.getScore());
        Director_TextBox.setText(review.getDirector());
        Genre_DropDown.setSelectedItem(review.getGenre());
        Favorite_CheckBox.setSelected(review.isFavorite());
        Notes_TextBox.setText(""); // anything typed here gets ADDED to the notes on update
        setTitle("Media Reviewer Log - Editing #" + review.getId());
    }

    public void clearForm() {
        Title_TextBox.setText("");
        Director_TextBox.setText("");
        Notes_TextBox.setText("");
        Rating_DropDown.setSelectedIndex(0);
        Genre_DropDown.setSelectedIndex(0);
        Favorite_CheckBox.setSelected(false);
        setTitle("Media Reviewer Log");
        if (reviewTable != null) {
            reviewTable.clearSelection();
        }
    }

    private void setDropDownFromScore(double score) {
        int index = (int) Math.round(score * 2) - 1;
        if (index < 0) {
            index = 0;
        }
        if (index > 9) {
            index = 9;
        }
        Rating_DropDown.setSelectedIndex(index);
    }

